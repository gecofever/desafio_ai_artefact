def render(conversation: dict[str, Any]) -> str:
    lines = [
        f"# {conversation['title']}",
        "",
        f"- Model: `{OPENAI_MODEL}`",
        f"- Captured: {datetime.now().strftime('%Y-%m-%d %H:%M')} (America/Campo_Grande)",
        "- Generated by `scripts/run_transcripts.py` against the live model;",
        "  tool arguments and results are shown exactly as the model saw them.",
        "",
    ]

    history: list[dict[str, str]] = []
    for index, message in enumerate(conversation["turns"], start=1):
        result = run_turn(message, history)
        lines.append(f"**Customer ({index}):** {message}")
        lines.append("")
        lines.append(f"**Assistant:** {result['reply']}")
        lines.append("")
        if result["tool_calls"]:
            lines.append("<details><summary>Tool calls</summary>")
            lines.append("")
            for call in result["tool_calls"]:
                lines.append(f"- `{call['name']}` with arguments:")
                lines.append("")
                lines.append("```json")
                lines.append(json.dumps(call["arguments"], ensure_ascii=False, indent=2))
                lines.append("```")
                lines.append("")
                lines.append("  result:")
                lines.append("")
                lines.append("```json")
                try:
                    pretty = json.dumps(
                        json.loads(call["result"]), ensure_ascii=False, indent=2
                    )
                except (json.JSONDecodeError, TypeError):
                    pretty = str(call["result"])
                lines.append(pretty[:3000])
                lines.append("```")
                lines.append("")
            lines.append("</details>")
            lines.append("")
        history += [
            {"role": "user", "content": message},
            {"role": "assistant", "content": result["reply"]},
        ]

    return "\n".join(lines)


def main() -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    only = sys.argv[1] if len(sys.argv) > 1 else None

    for conversation in CONVERSATIONS:
        if only and not conversation["slug"].startswith(only):
            continue
        print(f"recording {conversation['slug']} ...", flush=True)
        content = render(conversation)
        path = OUTPUT_DIR / f"{conversation['slug']}.md"
        path.write_text(content, encoding="utf-8")
        print(f"  -> {path.relative_to(REPO_ROOT)} ({len(content)} chars)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
