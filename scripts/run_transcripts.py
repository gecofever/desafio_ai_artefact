"""Record the example conversations in docs/conversations/.

Every transcript in this repository is produced by this script, against the
live model - none is hand-written. That is the point: a written transcript
proves nothing about the system, a captured one proves the whole path (prompt,
tools, database, policy engine, retrieval) worked on that date.

    python scripts/run_transcripts.py            # all conversations
    python scripts/run_transcripts.py 03         # only the one whose file starts with 03
"""

